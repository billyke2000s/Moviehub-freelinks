package local.tv.home;

import java.io.*;
import java.net.*;
import javax.net.ssl.SSLException;

/** Fixed, safe diagnostics. Never copies exception messages, URLs, responses or credentials into UI. */
final class ProviderFailure extends IOException {

    final String summary;

    private ProviderFailure(String summary, Throwable cause) {
        super(summary, cause);
        this.summary = summary;
    }

    static ProviderFailure from(Throwable cause) {
        return new ProviderFailure(describe(cause), cause);
    }

    static ProviderFailure http(int status, Throwable cause) {
        return status >= 400 && status <= 599
            ? new ProviderFailure("Provider returned HTTP " + status, cause)
            : from(cause);
    }

    static ProviderFailure transport(String summary, Throwable cause) {
        // Only summaries generated by this class are accepted; a response cannot supply UI text.
        for (String allowed : new String[] {
            "DNS lookup failed",
            "Connection timed out",
            "TLS connection failed",
            "Connection failed",
        })
            if (allowed.equals(summary)) return new ProviderFailure(allowed, cause);
        return from(cause);
    }

    static String describe(Throwable error) {
        int depth = 0;
        for (Throwable cause = error; cause != null && depth++ < 8; cause = cause.getCause()) {
            if (cause instanceof ProviderFailure) return ((ProviderFailure) cause).summary;
            if (cause instanceof UnknownHostException) return "DNS lookup failed";
            if (cause instanceof SocketTimeoutException) return "Connection timed out";
            if (cause instanceof SSLException) return "TLS connection failed";
            if (cause instanceof ConnectException) return "Connection failed";
            if (cause instanceof OutOfMemoryError) return "Provider ran out of memory";
            if (cause instanceof SecurityException) return "Android denied provider access";
            if (cause.getClass().getSimpleName().equals("Deadline")) return "Provider processing timed out";
            String name = cause.getClass().getSimpleName();
            if (
                name.equals("DeadObjectException") || name.equals("RemoteException")
            ) return "Provider process disconnected";
            String message = cause.getMessage();
            if (message == null) continue;
            // The isolated service emits only a sanitized chain of types/code locations.
            if (message.startsWith("Provider operation failed / ")) {
                if (message.contains("Deadline")) return "Provider processing timed out";
                if (message.contains("OutOfMemoryError")) return "Provider ran out of memory";
                if (message.contains("SecurityException")) return "Android denied provider access";
            }
            if (message.equals("Provider operation timeout")) return "Provider refresh timed out";
            if (message.equals("Provider startup failed")) return "Provider process did not start";
            if (message.equals("Provider service unavailable")) return "Provider process unavailable";
            if (
                message.equals("Provider input limit") ||
                message.equals("Provider limit") ||
                message.equals("Provider response limit") ||
                message.equals("Provider aggregate limit")
            ) return "Provider response exceeded size limit";
            if (
                message.equals("Provider HTTP capability rejected")
            ) return "Provider address blocked by app rules";
        }
        return "Provider error (" + error.getClass().getSimpleName() + ")";
    }
}
